/**
 * `as const` deja los valores como tipos literales, lo que obligaría al inglés
 * a repetir el texto en español. Widen conserva la forma del objeto pero
 * ensancha los literales a `string`, que es la restricción que interesa: mismas
 * claves, mismas listas, cualquier texto.
 */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer U)[]
        ? readonly Widen<U>[]
        : { -readonly [K in keyof T]: Widen<T[K]> };

